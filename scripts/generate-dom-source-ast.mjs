import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import generateModule from '@babel/generator';
import { parse } from '@babel/parser';
import traverseModule from '@babel/traverse';
import * as t from '@babel/types';

const traverse = traverseModule.default ?? traverseModule;
const generate = generateModule.default ?? generateModule;
const projectRoot = process.cwd();
const sourceFile = 'src/app/dom-source-lab/ast/Fixture.source.tsx';
const generatedFile = 'src/app/dom-source-lab/ast/Fixture.generated.tsx';
const mappingFile = 'src/app/dom-source-lab/ast/fixture-map.json';

function getStructuralPath(nodePath) {
  return nodePath
    .getAncestry()
    .reverse()
    .map((ancestor) => `${ancestor.listKey ?? 'node'}:${String(ancestor.key)}`)
    .join('/');
}

function createNodeId(nodePath, tagName) {
  const identity = `${sourceFile}:${tagName}:${getStructuralPath(nodePath)}`;
  return `ast_${createHash('sha1').update(identity).digest('hex').slice(0, 10)}`;
}

const sourceCode = await readFile(path.join(projectRoot, sourceFile), 'utf8');
const ast = parse(sourceCode, {
  sourceType: 'module',
  sourceFilename: sourceFile,
  plugins: ['jsx', 'typescript'],
});
const sourceMap = {};

traverse(ast, {
  JSXOpeningElement(nodePath) {
    const { name, loc, attributes } = nodePath.node;
    if (!t.isJSXIdentifier(name) || !/^[a-z]/.test(name.name) || !loc) return;

    const alreadyMarked = attributes.some(
      (attribute) => t.isJSXAttribute(attribute)
        && t.isJSXIdentifier(attribute.name, { name: 'data-source-id' }),
    );
    if (alreadyMarked) return;

    const nodeId = createNodeId(nodePath, name.name);
    const sourceNode = nodePath.parentPath?.isJSXElement()
      ? nodePath.parentPath.node
      : nodePath.node;
    const end = sourceNode.loc?.end ?? loc.end;

    sourceMap[nodeId] = {
      file: sourceFile,
      start: { line: loc.start.line, column: loc.start.column + 1 },
      end: { line: end.line, column: end.column + 1 },
      nodeId,
      tagName: name.name,
      confidence: 1,
    };

    attributes.push(
      t.jsxAttribute(t.jsxIdentifier('data-source-id'), t.stringLiteral(nodeId)),
    );
  },
});

const output = generate(ast, { comments: true }, sourceCode);
await writeFile(
  path.join(projectRoot, generatedFile),
  `// Generated by scripts/generate-dom-source-ast.mjs. Do not edit.\n${output.code}\n`,
);
await writeFile(
  path.join(projectRoot, mappingFile),
  `${JSON.stringify(sourceMap, null, 2)}\n`,
);

console.log(`Generated ${Object.keys(sourceMap).length} AST source mappings.`);
